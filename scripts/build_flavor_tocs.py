#!/usr/bin/env python3
"""Build (or --check) the WoW Forever release files from the retail ones.

Port of Warband Nexus scripts/build_flavor_tocs.py.

Retail and WoW Forever are separate releases of one CurseForge / Wago project: separate versions,
tags, changelogs and zips (retail: tag vX.Y.Z; Forever: tag forever-vX.Y.Z).

  ArtisanNexus.toc           retail (## Interface: 120105) -- the source of truth, edited by hand
  ArtisanNexus_Forever.toc   WoW Forever (## Interface: 16001) -- GENERATED by this script
  ArtisanNexus_Camelot.toc   the same file under Forever's other game-type suffix -- GENERATED
  .pkgmeta                   retail package -- edited by hand
  .pkgmeta-forever           Forever package -- GENERATED: .pkgmeta without its BEGIN/END
                             retail-only block, CHANGELOG_FOREVER.md as the changelog, the
                             RETAIL_ONLY Lua files ignored (release.yml swaps ArtisanNexus.toc
                             for the Forever TOC in CI before packaging)

The Forever TOC's ## Version is FOREVER_ADDON_VERSION from Modules/Constants.lua.

The Forever client picks _Forever.toc / _Camelot.toc over the plain one (warcraft.wiki.gg
TOC_format; "the Camelot value may be changed to Forever in the future", so both ship).

The Forever TOC is the retail TOC minus RETAIL_ONLY below: files for systems Forever does not
have (gathering overload, concentration, crafting orders). Every file left in loads without them --
the callers guard each entry point (Core.lua, the UI.lua tab gate, SettingsSchema, ...). Adding a
new file to ArtisanNexus.toc puts it in both builds; list it here if it is retail-only.

Bindings.xml is auto-loaded from the addon root by every TOC, so it cannot be split per flavor;
release.yml deletes the overload binding from it in the Forever package (its button is retail-only).

Usage:
  python scripts/build_flavor_tocs.py           write the Forever TOCs
  python scripts/build_flavor_tocs.py --check   fail if they are stale (CI / preflight)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RETAIL_TOC = ROOT / "ArtisanNexus.toc"
FOREVER_TOCS = (ROOT / "ArtisanNexus_Forever.toc", ROOT / "ArtisanNexus_Camelot.toc")
FOREVER_INTERFACE = "16001"
CONSTANTS = ROOT / "Modules" / "Constants.lua"
RETAIL_PKGMETA = ROOT / ".pkgmeta"
FOREVER_PKGMETA = ROOT / ".pkgmeta-forever"

# Retail-only files: never loaded on WoW Forever. Paths as written in ArtisanNexus.toc.
RETAIL_ONLY = (
    # Gathering overload: a Midnight node mechanic (Midnight object templates, secure cast button,
    # cooldown HUD). Core.lua / LootHistoryUI / SettingsSchema guard every entry point.
    r"Modules\Data\GatheringNodeOverloadRegistry.lua",
    r"Modules\Gathering\GatheringOverloadService.lua",
    r"Modules\Gathering\GatheringOverloadActionButton.lua",
    r"Modules\UI\GatheringOverloadIndicator.lua",
    # Concentration planner + its Hub tab (callers read ns.ConcentrationPlannerService nil-safe;
    # the tab is hidden by Capabilities "concentration")
    r"Modules\Economy\ConcentrationPlannerService.lua",
    r"Modules\UI\Hub\Pages\ConcentrationPage.lua",
    # Crafting orders + its Hub tab (hidden by Capabilities "craftingOrders")
    r"Modules\Economy\CraftingOrdersService.lua",
    r"Modules\UI\Hub\Pages\OrdersPage.lua",
)

HEADER = (
    "# GENERATED by scripts/build_flavor_tocs.py from ArtisanNexus.toc -- do not edit by hand.\n"
    "# WoW Forever build: ArtisanNexus.toc minus the retail-only files listed in that script.\n"
)


def forever_version() -> str:
    m = re.search(r'FOREVER_ADDON_VERSION\s*=\s*"([^"]+)"', CONSTANTS.read_text(encoding="utf-8"))
    if not m:
        raise SystemExit("FOREVER_ADDON_VERSION not found in Modules/Constants.lua")
    return m.group(1)


def build_forever_pkgmeta(retail_text: str) -> str:
    out, skipping = [], False
    for ln in retail_text.splitlines():
        if ln.strip().startswith("# BEGIN retail-only"):
            skipping = True
            continue
        if ln.strip().startswith("# END retail-only"):
            skipping = False
            continue
        if skipping:
            continue
        if ln.strip() == "filename: CHANGELOG.md":
            ln = ln.replace("CHANGELOG.md", "CHANGELOG_FOREVER.md")
        out.append(ln)
    if skipping or "CHANGELOG_FOREVER.md" not in "\n".join(out):
        raise SystemExit(".pkgmeta: missing END retail-only marker or manual-changelog filename")
    while out and not out[-1].strip():
        out.pop()
    # ArtisanNexus.toc stays: release.yml overwrites it with the Forever TOC before packaging
    # (the packager validates the game version against the package-as TOC).
    out.append("  # WoW Forever package: no retail changelog or retail-only Lua files.")
    out.append("  - CHANGELOG.md")
    for rel in RETAIL_ONLY:
        out.append("  - " + rel.replace("\\", "/"))
    return ("# GENERATED by scripts/build_flavor_tocs.py from .pkgmeta -- do not edit by hand.\n"
            + "\n".join(out) + "\n")


def build_forever_toc(retail_text: str) -> str:
    lines = retail_text.splitlines()
    present = {ln.strip() for ln in lines}
    missing = [f for f in RETAIL_ONLY if f not in present]
    if missing:
        raise SystemExit("RETAIL_ONLY lists files not in ArtisanNexus.toc: " + ", ".join(missing))
    excluded = set(RETAIL_ONLY)
    out = []
    for ln in lines:
        if ln.strip() in excluded:
            continue
        if re.match(r"^## Interface:", ln):
            ln = "## Interface: " + FOREVER_INTERFACE
        elif re.match(r"^## Version:", ln):
            ln = "## Version: " + forever_version()
        out.append(ln)
    return HEADER + "\n".join(out) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    retail_text = RETAIL_TOC.read_text(encoding="utf-8-sig")
    m = re.search(r"(?m)^## Interface:\s*(.+)$", retail_text)
    if not m or FOREVER_INTERFACE in m.group(1):
        print(f"ArtisanNexus.toc must be retail-only (## Interface without {FOREVER_INTERFACE}).",
              file=sys.stderr)
        return 1
    expected_toc = build_forever_toc(retail_text)
    targets = [(path, expected_toc) for path in FOREVER_TOCS]
    targets.append((FOREVER_PKGMETA, build_forever_pkgmeta(RETAIL_PKGMETA.read_text(encoding="utf-8-sig"))))
    stale = []
    for path, expected in targets:
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != expected:
            if check:
                stale.append(path.name)
            else:
                path.write_text(expected, encoding="utf-8", newline="\n")
                print(f"wrote {path.name}")
    if stale:
        print("Forever release files are stale (run python scripts/build_flavor_tocs.py): "
              + ", ".join(stale), file=sys.stderr)
        return 1
    if check:
        kept = sum(1 for ln in expected_toc.splitlines()
                   if ln.strip().lower().endswith(".lua") and not ln.lstrip().startswith("#"))
        print(f"Flavor TOCs OK - Forever v{forever_version()} loads {kept} Lua files, "
              f"{len(RETAIL_ONLY)} retail-only left out.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
